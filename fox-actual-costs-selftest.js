'use strict';
const assert=require('node:assert/strict');
const c=require('./fox-actual-costs.js');
let w=c.windowFor('2026-10-26');
assert.equal(new Date(w.start).toISOString(),'2026-10-25T23:30:00.000Z');
assert.equal(new Date(w.end).toISOString(),'2026-10-26T23:30:00.000Z');
assert.equal(c.windowFor('2026-10-25').end-c.windowFor('2026-10-25').start,25*3600000);
assert.equal(c.windowFor('2026-03-29').end-c.windowFor('2026-03-29').start,23*3600000);
assert.equal(c.latestEndDay(Date.parse('2026-10-27T17:00Z')),'2026-10-26');
assert.equal(c.latestEndDay(Date.parse('2026-10-27T23:30Z')),'2026-10-27');
assert.throws(()=>c.windowFor('2026-02-30'));
const rows=Array.from({length:48},(_,i)=>({start:w.start+i*1800000,end:w.start+(i+1)*1800000,value:1,measured:true}));
assert.equal(c.total(rows,w,w.end),48);
assert.equal(c.total([],w,w.end),null);
assert.equal(c.total(rows.slice(1),w,w.end),null);
assert.equal(c.total([...rows,rows[0]],w,w.end),null);
assert.equal(c.total(rows,w,w.end-1),null);
assert.equal(c.total(rows.map(r=>({...r,measured:false})),w,w.end),null);
assert.equal(c.total(rows.map(r=>({...r,value:0})),w,w.end),0);
console.log('ACTUAL COSTS PASS: UK accounting boundaries, DST, missing/duplicate/forecast rejection and measured zero');
