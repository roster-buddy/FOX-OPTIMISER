'use strict';
const assert=require('node:assert/strict');
const m=require('./fox-backtest-v21.js');
const c={capacity:10.24,load:.3,chargeKW:5,dischargeKW:5,exportKW:3.5,pv:2.01,inverterKW:1.5,pr:.82,eff:.95,importP:28,nightP:3.33,min:5,target:20,soc:100,derate:0,tilt:35,bearing:110,scenario:'low'};
const n={importKW:8.3,evKWh:13,evKW:6.6,nightHomeKW:.3,wearP:5};
assert.equal(m.version,'2.1');
assert.equal(m.overnightSlotsFor('2026-10-25').length,12);
assert.equal(m.overnightSlotsFor('2026-10-24').length,14);
assert.equal(m.overnightSlotsFor('2026-03-28').length,10);
for(const date of ['2026-10-25','2026-10-24','2026-03-28']){
 const z=m.overnightCharge(c,date,.62,n);
 assert(z.ok,'night feasibility: '+date);
 assert(Math.abs(z.final-c.capacity)<1e-8);
 assert(Math.abs(z.batteryGrid-(c.capacity-.62)/c.eff)<1e-8);
 assert(Math.abs(z.evDelivered-13)<1e-8);
 for(const x of z.rows)assert(x.gridKW<=n.importKW+1e-9);
}
const highEv=m.overnightCharge(c,'2026-10-25',.62,{...n,evKWh:43});
assert.equal(highEv.ok,false);
assert(highEv.batteryMissing>0);
const capped=m.overnightCharge(c,'2026-10-25',.62,{...n,importKW:3});
assert.equal(capped.ok,false);
const s=m.slotsFor('2026-10-18');
const prices=s.map(z=>z.clock>=16.5&&z.clock<18.5?38:8);
const irr=s.map(z=>z.clock>=9&&z.clock<15?.1:0);
const r=m.compare(c,s,irr,prices);
assert(r.ok);
const adjusted=m.adjustedCompare(r,c,'2026-10-18',n);
assert(adjusted.ok,adjusted.reason);
assert(Math.abs(adjusted.gross-adjusted.net-adjusted.wearCost)<1e-10);
assert(Math.abs(adjusted.baseFullCost-adjusted.optFullCost-adjusted.net)<1e-8);
assert(adjusted.base.peak<=8.3+1e-9);
assert(adjusted.opt.peak<=8.3+1e-9);
assert(adjusted.wearCost>=0);
assert.equal(m.adjustedCompare(r,c,'2026-10-18',{...n,evKWh:43}).ok,false);
const free=m.adjustedCompare(r,c,'2026-10-18',{...n,wearP:0});
assert(Math.abs(free.net-r.improvement)<1e-10);
assert(m.compare(c,s,new Array(36).fill(0),new Array(36).fill(-10)).optimised.forced===0);
console.log('ALL V2.1 TESTS PASS: DST 10/12/14 slots, night charging, shared ceiling, EV stress, no double counting, wear cost');
console.log('Representative gross/net',adjusted.gross.toFixed(3),adjusted.net.toFixed(3),'Peak kW',adjusted.opt.peak.toFixed(2));
