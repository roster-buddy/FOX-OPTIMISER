'use strict';
const assert=require('node:assert/strict');
const dates=require('./fox-actual-costs.js'),report=require('./fox-actual-report.js');
const day='2026-10-26',w=dates.windowFor(day);
const stream=(source,value)=>Array.from({length:48},(_,i)=>({start:w.start+i*1800000,end:w.start+(i+1)*1800000,value,source,measured:true}));
const rate=pence=>[{...w,pence,confirmed:true}];
const input={streams:{gridImport:stream('octopus',1),gridExport:stream('octopus',.1)},tariffs:{import:rate(23.2995),export:rate(12)}};
let r=report.build(day,input,w.end);
assert(r.gridImport.available&&r.gridExport.available);
assert(Math.abs(r.gridImport.cost-48*.232995)<1e-9);
assert.equal(r.batteryCharge.available,false);
assert.equal(r.cashBalance.available,false);
assert.equal(r.savings.value,null);
assert(r.gridBalance.available);
input.streams.batteryGridCharge=stream('fox',.2);
input.streams.evGridCharge=stream('ohme',.1);
r=report.build(day,input,w.end);
assert(r.cashBalance.available);
assert(Math.abs(r.cashBalance.value-(4.8*.12-14.4*.232995))<1e-9);
input.streams.evGridCharge.pop();r=report.build(day,input,w.end);
assert(!r.cashBalance.available&&r.gridImport.available);
input.tariffs.export=[];r=report.build(day,input,w.end);
assert(!r.gridExport.available&&r.gridImport.available);
assert(Math.abs(r.gridExport.total-4.8)<1e-9);
assert.equal(report.build(day,{},w.end).gridBalance.value,null);
assert.equal(report.build(day,input,w.end-1).gridImport.available,false);
console.log('ACTUAL REPORT PASS: independent measured totals, exact pricing, cash balance and unavailable savings');
